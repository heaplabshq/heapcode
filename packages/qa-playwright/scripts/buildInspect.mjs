import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

/**
 * Bundle `@heapcode/page`'s in-page entries into the strings the driver injects:
 * the inspector (always) and the recorder (while recording).
 *
 * An injected script has no module loader, so it has to be one classic
 * script. Generated into src/ and committed, so running from source (tests,
 * the CLI's own bundle) needs no build step; `test/inspectBundle.test.ts`
 * fails when this file is stale.
 */
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = resolve(ROOT, 'src/inspectBundle.generated.ts');

async function bundle(entry) {
  const result = await build({
    entryPoints: [resolve(ROOT, '../page/src', entry)],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'chrome110',
    minify: true,
    legalComments: 'none',
  });
  return result.outputFiles[0].text.trim();
}

export async function bundleInspect() {
  return (
    '// Generated by scripts/buildInspect.mjs from @heapcode/page — do not edit.\n' +
    '// Run `pnpm --filter @heapcode/qa-playwright build:inspect` after changing @heapcode/page.\n' +
    `export const INSPECT_BUNDLE = ${JSON.stringify(await bundle('browserEntry.ts'))};\n` +
    `export const RECORDER_BUNDLE = ${JSON.stringify(await bundle('recorderEntry.ts'))};\n`
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, await bundleInspect());
  console.log('src/inspectBundle.generated.ts');
}
