import type { Expectation, Flow, Locator, Step } from './flow.js';

/**
 * A flow as a plain Playwright test (`@playwright/test`), so the tests are
 * never locked in: a team can keep the `.spec.ts` files and drop Heap QA.
 *
 * What does not carry over is what Heap QA adds on top: healing, the
 * strategy ladder (the export uses the step's most stable strategy — test id,
 * then role and name, label, placeholder, text, CSS), fingerprints and the
 * reports. Inputs become a const, secrets read `process.env`, `{{runId}}` is
 * the run's timestamp, and reusable steps become helper functions.
 */

export const EXPORT_HEADER = '// Generated by `heapcode qa export` from';

export interface ExportOptions {
  /** Default base URL, overridable with BASE_URL when the test runs. */
  baseUrl?: string;
}

/** Which helper functions a flow needs: the reusable steps it uses, transitively. */
function usedSteps(flow: Flow, library: Map<string, Flow>, seen = new Set<string>()): string[] {
  for (const step of flow.steps) {
    if (step.kind !== 'use' || seen.has(step.use)) continue;
    const target = library.get(step.use);
    if (!target) continue;
    seen.add(step.use);
    usedSteps(target, library, seen);
  }
  return [...seen];
}

export function exportPlaywright(id: string, flow: Flow, library: Map<string, Flow>, options: ExportOptions = {}): string {
  const helpers = usedSteps(flow, library);
  const needsConsole = [flow, ...helpers.map((h) => library.get(h)!)].some((f) => f.steps.some((s) => s.kind === 'expect' && s.expect.kind === 'noConsoleErrors'));
  const needsServer = [flow, ...helpers.map((h) => library.get(h)!)].some((f) => f.steps.some((s) => s.kind === 'expect' && s.expect.kind === 'noServerErrors'));
  const out: string[] = [
    `${EXPORT_HEADER} ${flow.file ?? `flows/${id}.yaml`}.`,
    '// Edits here are overwritten by the next export; change the flow instead, or stop exporting it.',
    "import { test, expect, type Page } from '@playwright/test';",
    '',
    `const BASE_URL = process.env.BASE_URL ?? ${js(options.baseUrl ?? 'http://localhost:3000')};`,
    'const runId = String(Date.now());',
    'const url = (path: string): string => new URL(path, BASE_URL.endsWith(\'/\') ? BASE_URL : `${BASE_URL}/`).toString();',
    '',
  ];
  if (needsConsole || needsServer) {
    out.push(
      '/** What the page reported along the way, for the no-errors checks. */',
      'const seen = { console: [] as string[], server: [] as string[] };',
      'function watch(page: Page): void {',
      "  page.on('console', (m) => { if (m.type() === 'error' && !m.location().url.endsWith('/favicon.ico')) seen.console.push(m.text()); });",
      "  page.on('pageerror', (e) => seen.console.push(`Uncaught ${e.message}`));",
      "  page.on('response', (r) => { if (r.status() >= 500) seen.server.push(`${r.request().method()} ${r.url()} → ${r.status()}`); });",
      "  page.on('requestfailed', (r) => seen.server.push(`${r.method()} ${r.url()} → ${r.failure()?.errorText ?? 'failed'}`));",
      '}',
      '',
    );
  }
  for (const name of helpers) {
    const step = library.get(name)!;
    out.push(
      `/** ${step.name} — steps/${name}.yaml */`,
      `async function ${fnName(name)}(page: Page, given: Record<string, string> = {}): Promise<void> {`,
      // Its own defaults, for whatever the caller did not pass — in order, so a
      // default may use an earlier one.
      '  const inputs: Record<string, string> = { ...given };',
      ...Object.entries(step.inputs).map(([k, v]) => `  inputs[${js(k)}] ??= ${template(v, 'inputs')};`),
      ...body(step.steps, 'inputs', '  '),
      '}',
      '',
    );
  }
  out.push(`test(${js(flow.name)}, async ({ page }) => {`);
  if (needsConsole || needsServer) out.push('  watch(page);');
  out.push('  const inputs: Record<string, string> = {};', ...Object.entries(flow.inputs).map(([k, v]) => `  inputs[${js(k)}] = ${template(v, 'inputs')};`));
  out.push(...body(flow.steps, 'inputs', '  '), '});', '');
  return out.join('\n');

  function body(steps: Step[], inputsVar: string, indent: string): string[] {
    const lines: string[] = [];
    for (const step of steps) {
      if (step.intent) lines.push(`${indent}// ${step.intent.replace(/\n/g, ' ')}`);
      lines.push(...stepLines(step, inputsVar, indent));
    }
    return lines;
  }

  function stepLines(step: Step, inputsVar: string, indent: string): string[] {
    const t = (text: string): string => template(text, inputsVar);
    switch (step.kind) {
      case 'goto':
        return [`${indent}await page.goto(url(${t(step.url)}));`];
      case 'click':
        return [`${indent}await ${locator(step.target)}.click();`];
      case 'type':
        return [`${indent}await ${locator(step.target)}.${step.clear ? 'fill' : 'pressSequentially'}(${t(step.text)});`];
      case 'select':
        return [`${indent}await ${locator(step.target)}.selectOption({ label: ${t(step.option)} });`];
      case 'press':
        return [step.target ? `${indent}await ${locator(step.target)}.press(${js(step.key)});` : `${indent}await page.keyboard.press(${js(step.key)});`];
      case 'wait':
        return [`${indent}await page.waitForTimeout(${step.ms});`];
      case 'use': {
        const given = Object.entries(step.inputs).map(([k, v]) => `${js(k)}: ${t(v)}`);
        return [`${indent}await ${fnName(step.use)}(page${given.length ? `, { ${given.join(', ')} }` : ''});`];
      }
      case 'expect':
        return [`${indent}${expectation(step.expect, t)}`];
    }
  }
}

function expectation(e: Expectation, t: (s: string) => string): string {
  switch (e.kind) {
    case 'visible':
      return `await expect(${locator(e.target)}).toBeVisible();`;
    case 'hidden':
      return `await expect(${locator(e.target)}).toBeHidden();`;
    case 'text':
      return e.equals !== undefined ? `await expect(${locator(e.target)}).toHaveText(${t(e.equals)});` : `await expect(${locator(e.target)}).toContainText(${t(e.contains!)});`;
    case 'url':
      if (e.equals !== undefined) return `await expect(page).toHaveURL(url(${t(e.equals)}));`;
      if (e.contains !== undefined) return `await expect(page).toHaveURL((u) => u.toString().includes(${t(e.contains)}));`;
      return `await expect(page).toHaveURL(new RegExp(${js(e.matches!)}));`;
    case 'count':
      return `await expect(${locator(e.target)}).toHaveCount(${e.equals});`;
    case 'noConsoleErrors':
      return 'expect(seen.console, "the page logged errors").toEqual([]);';
    case 'noServerErrors':
      return 'expect(seen.server, "requests failed").toEqual([]);';
    case 'screenshot':
      // Playwright keeps its own baselines (made on its first run), not Heap QA's.
      return `await expect(${e.target ? locator(e.target) : 'page'}).toHaveScreenshot(${js(`${e.name}.png`)}, { maxDiffPixelRatio: ${(e.maxDiff ?? 1) / 100}, animations: 'disabled' });`;
  }
}

/** The step's most stable strategy, as Playwright writes it. Exact matching, as replay does. */
export function locator(l: Locator): string {
  let base: string;
  if (l.testId !== undefined) base = `page.getByTestId(${js(l.testId)})`;
  else if (l.role !== undefined) base = `page.getByRole(${js(l.role)}${l.name !== undefined ? `, { name: ${js(l.name)}, exact: true }` : ''})`;
  else if (l.label !== undefined) base = `page.getByLabel(${js(l.label)}, { exact: true })`;
  else if (l.placeholder !== undefined) base = `page.getByPlaceholder(${js(l.placeholder)}, { exact: true })`;
  else if (l.text !== undefined) base = `page.getByText(${js(l.text)}, { exact: true })`;
  else base = `page.locator(${js(l.css ?? '')})`;
  return l.nth !== undefined ? `${base}.nth(${l.nth})` : base;
}

/** A flow template as a JS template literal: `{{x}}`, `{{secret:X}}`, `{{runId}}`, `${ENV:-default}`. */
export function template(text: string, inputsVar: string): string {
  const PATTERN = /\{\{\s*([^}]+?)\s*\}\}|\$\{([A-Za-z_][A-Za-z0-9_]*)(?::-([^}]*))?\}/g;
  let out = '';
  let last = 0;
  let dynamic = false;
  for (const m of text.matchAll(PATTERN)) {
    out += escapeTemplate(text.slice(last, m.index));
    last = m.index! + m[0].length;
    dynamic = true;
    const [, expr, env, envDefault] = m;
    if (env !== undefined) out += `\${process.env[${js(env)}] ?? ${js(envDefault ?? '')}}`;
    else if (expr!.startsWith('secret:')) out += `\${process.env[${js(expr!.slice(7).trim())}] ?? ''}`;
    else if (expr === 'runId') out += '${runId}';
    else out += `\${${inputsVar}[${js(expr!)}]}`;
  }
  out += escapeTemplate(text.slice(last));
  return dynamic ? `\`${out}\`` : js(text);
}

function escapeTemplate(s: string): string {
  return s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

function js(s: string): string {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
}

function fnName(step: string): string {
  const parts = step.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const name = parts.map((p, i) => (i === 0 ? p.toLowerCase() : p[0]!.toUpperCase() + p.slice(1).toLowerCase())).join('');
  return /^[a-z_]/.test(name) ? `step_${name}` : `step_${name || 'unnamed'}`;
}
